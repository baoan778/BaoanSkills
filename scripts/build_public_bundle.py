#!/usr/bin/env python3
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

from _skill_utils import repo_root
from check_publication import parse_allowlist, validate_publication

TOP_LEVEL_FILES = (
    ".editorconfig",
    ".gitattributes",
    ".gitignore",
    ".pre-commit-config.yaml",
    "CHANGELOG.md",
    "CODE_OF_CONDUCT.md",
    "CONTRIBUTING.md",
    "LICENSE",
    "NOTICE",
    "README.md",
    "SECURITY.md",
    "pyproject.toml",
    "requirements-dev.txt",
)
TOP_LEVEL_DIRS = (
    ".github",
    "docs",
    "licenses",
    "release",
    "scripts",
    "tests",
)
IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc", "*.pyo", ".DS_Store", "Thumbs.db")
TRANSIENT_DIRS = frozenset({".pytest_cache", ".ruff_cache", ".mypy_cache", "__pycache__"})
TRANSIENT_FILES = frozenset({".coverage"})
TRANSIENT_SUFFIXES = frozenset({".pyc", ".pyo"})


def run(command: list[str], cwd: Path) -> None:
    display = " ".join(command)
    print(f"RUN {display}")
    env = os.environ.copy()
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    subprocess.run(command, cwd=cwd, check=True, env=env)


def transient_artifacts(root: Path) -> list[Path]:
    """Return runtime caches that must not ship in a release snapshot."""
    resolved_root = root.resolve()
    found: list[Path] = []
    for path in resolved_root.rglob("*"):
        if not path.is_relative_to(resolved_root):
            continue
        if path.name in TRANSIENT_DIRS or path.name in TRANSIENT_FILES or path.suffix in TRANSIENT_SUFFIXES:
            found.append(path)
    return found


def remove_transient_artifacts(root: Path) -> int:
    """Remove caches created while validating the copied snapshot."""
    resolved_root = root.resolve()
    removed = 0
    for path in sorted(resolved_root.rglob("*"), key=lambda item: len(item.parts), reverse=True):
        if not path.is_relative_to(resolved_root):
            continue
        if path.name in TRANSIENT_DIRS:
            if path.is_symlink():
                path.unlink()
            elif path.is_dir():
                shutil.rmtree(path)
            else:
                continue
            removed += 1
        elif path.is_file() and (path.name in TRANSIENT_FILES or path.suffix in TRANSIENT_SUFFIXES):
            path.unlink()
            removed += 1
    remaining = transient_artifacts(resolved_root)
    if remaining:
        raise SystemExit("transient artifacts remain in the public snapshot: " + ", ".join(str(p) for p in remaining))
    return removed


def prepare_output(source: Path, output: Path, force: bool) -> None:
    if output == source or output.is_relative_to(source):
        raise SystemExit("output must be outside the source repository")
    if output.exists():
        if not force:
            raise SystemExit(f"output already exists: {output}; use --force to replace it")
        if not output.name.endswith("-public"):
            raise SystemExit("refusing to remove an existing directory whose name does not end with '-public'")
        shutil.rmtree(output)
    output.mkdir(parents=True)


def copy_snapshot(source: Path, output: Path) -> int:
    for name in TOP_LEVEL_FILES:
        path = source / name
        if not path.is_file():
            raise SystemExit(f"required release file is missing: {name}")
        shutil.copy2(path, output / name)

    for name in TOP_LEVEL_DIRS:
        path = source / name
        if not path.is_dir():
            raise SystemExit(f"required release directory is missing: {name}")
        shutil.copytree(path, output / name, ignore=IGNORE)

    names, errors = parse_allowlist(source)
    if errors:
        raise SystemExit("invalid public allowlist: " + "; ".join(errors))
    skills_out = output / "skills"
    skills_out.mkdir()
    shutil.copy2(source / "skills" / ".gitignore", skills_out / ".gitignore")
    for name in names:
        source_skill = source / "skills" / name
        if not source_skill.is_dir():
            raise SystemExit(f"allowlisted skill is missing: {name}")
        shutil.copytree(source_skill, skills_out / name, ignore=IGNORE)

    (output / ".publication-snapshot").write_text(
        "Generated by scripts/build_public_bundle.py. Publish this directory, not the staging checkout.\n",
        encoding="utf-8",
        newline="\n",
    )
    return len(names)


def main() -> int:
    parser = argparse.ArgumentParser(description="Build and validate a clean public BaoanSkills snapshot.")
    parser.add_argument(
        "--output",
        type=Path,
        default=repo_root().parent / f"{repo_root().name}-public",
        help="destination directory (default: sibling '<repo>-public')",
    )
    parser.add_argument("--force", action="store_true", help="replace an existing output ending in '-public'")
    args = parser.parse_args()

    source = repo_root().resolve()
    output = args.output.resolve()
    source_errors = validate_publication(source, exclusive=False, require_lock=True)
    if source_errors:
        for error in source_errors:
            print(f"FAIL {error}")
        print("source publication check failed; clean snapshot was not built")
        return 1

    prepare_output(source, output, args.force)
    skill_count = copy_snapshot(source, output)
    print(f"copied {skill_count} allowlisted skills to {output}")

    python = sys.executable
    commands = [
        [python, "-m", "ruff", "check", "scripts", "tests"],
        [python, "-m", "pytest", "-q"],
        [python, "scripts/check_workflows.py"],
        [python, "scripts/apply_skill_quality.py", "--check"],
        [python, "scripts/generate_agent_metadata.py", "--check"],
        [python, "scripts/build_index.py", "--write"],
        [python, "scripts/build_provenance.py", "--write"],
        [python, "scripts/validate_skills.py", "--strict"],
        [python, "scripts/check_publication.py", "--check", "--exclusive"],
        [python, "scripts/check_links.py"],
        [python, "scripts/check_whitespace.py"],
        [python, "scripts/check_markdown_structure.py"],
        [python, "scripts/check_skill_layout.py"],
        [python, "scripts/check_resources.py"],
        [python, "scripts/check_encoding.py"],
        [python, "scripts/smoke_test_scripts.py"],
        [python, "scripts/build_index.py", "--check"],
        [python, "scripts/build_provenance.py", "--check"],
        [python, "scripts/build_kb_manifest.py", "--check"],
        [python, "scripts/check_release_readiness.py", "--strict", "--exclusive"],
    ]
    for command in commands:
        run(command, output)
    removed = remove_transient_artifacts(output)
    run([python, "scripts/check_publication.py", "--check", "--exclusive"], output)
    removed += remove_transient_artifacts(output)
    print(f"removed {removed} transient artifacts; public bundle validated successfully: {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
