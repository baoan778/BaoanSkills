#!/usr/bin/env python3
from __future__ import annotations

import argparse
import csv
import io
import sys
from dataclasses import dataclass

from _skill_utils import flatten, iter_skills, load_skill, metadata_of, normalized_license, repo_root


@dataclass
class Record:
    name: str
    license: str
    status: str
    author: str
    source: str
    source_repo: str
    upstream_commit: str
    upstream_path: str
    license_evidence: str
    retrieved_at: str
    modifications: str
    date_added: str
    risk: str
    license_status: str
    provenance_status: str


def collect_records() -> list[Record]:
    records: list[Record] = []
    for skill_dir in iter_skills():
        doc = load_skill(skill_dir)
        fm = doc.frontmatter
        metadata = metadata_of(fm)
        license_value = normalized_license(fm)
        author = flatten(metadata.get("author", "")) or "unknown"
        source = flatten(metadata.get("source", "")) or "unknown"
        source_repo = flatten(metadata.get("source_repo", "")) or ""
        upstream_commit = flatten(metadata.get("upstream_commit", "")) or ""
        upstream_path = flatten(metadata.get("upstream_path", "")) or ""
        license_evidence = flatten(metadata.get("license_evidence", "")) or ""
        retrieved_at = flatten(metadata.get("retrieved_at", "")) or ""
        modifications = flatten(metadata.get("modifications", "")) or ""
        date_added = flatten(metadata.get("date_added", "")) or ""
        risk = flatten(metadata.get("risk", "")) or "unknown"
        license_status = flatten(metadata.get("license_status", "")) or "unknown"
        provenance_status = flatten(metadata.get("provenance_status", "")) or "unknown"
        verified = (
            license_value != "NOASSERTION"
            and license_status == "verified"
            and provenance_status == "verified"
            and author != "unknown"
            and source != "unknown"
            and bool(license_evidence)
            and bool(retrieved_at)
            and bool(modifications)
        )
        records.append(
            Record(
                name=str(fm.get("name", skill_dir.name)),
                license=license_value,
                status="verified" if verified else "review-required",
                author=author,
                source=source,
                source_repo=source_repo,
                upstream_commit=upstream_commit,
                upstream_path=upstream_path,
                license_evidence=license_evidence,
                retrieved_at=retrieved_at,
                modifications=modifications,
                date_added=date_added,
                risk=risk,
                license_status=license_status,
                provenance_status=provenance_status,
            )
        )
    return sorted(records, key=lambda record: record.name)


def render_markdown(records: list[Record]) -> str:
    verified = sum(record.status == "verified" for record in records)
    review_required = len(records) - verified
    noassertion = sum(record.license == "NOASSERTION" for record in records)
    lines = [
        "# Provenance inventory",
        "",
        "> Generated by `scripts/build_provenance.py`. Do not edit manually.",
        "> `verified` means the license and provenance metadata passed the repository checks;",
        "> it is a release-control state, not a legal opinion.",
        "",
        f"- Total skills in release scope: **{len(records)}**",
        f"- Verified: **{verified}**",
        f"- Review required: **{review_required}**",
        f"- License `NOASSERTION`: **{noassertion}**",
        "",
        "| Skill | License | Verification | Author | Source repository | Upstream commit | Evidence | Retrieved |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for record in records:
        values = [
            record.name,
            record.license,
            f"{record.status} ({record.license_status}/{record.provenance_status})",
            record.author,
            record.source_repo or "local/original",
            record.upstream_commit or "n/a",
            record.license_evidence,
            record.retrieved_at,
        ]
        lines.append("| " + " | ".join(value.replace("|", "\\|") for value in values) + " |")

    lines.extend(["", "## Modification notes", ""])
    for record in records:
        lines.append(f"- **{record.name}**: {record.modifications or 'not documented'}")

    lines.extend(
        [
            "",
            "## Release rule",
            "",
            "Only skills with `verification: verified` may enter the public allowlist.",
            "Skills with `NOASSERTION` or incomplete provenance remain local staging content",
            "and must not be included in a public bundle.",
            "",
        ]
    )
    return "\n".join(lines)


def render_csv(records: list[Record]) -> str:
    buffer = io.StringIO(newline="")
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(
        [
            "skill",
            "license",
            "verification",
            "license_status",
            "provenance_status",
            "author",
            "source",
            "source_repo",
            "upstream_commit",
            "upstream_path",
            "license_evidence",
            "retrieved_at",
            "modifications",
            "date_added",
            "risk",
        ]
    )
    for record in records:
        writer.writerow(
            [
                record.name,
                record.license,
                record.status,
                record.license_status,
                record.provenance_status,
                record.author,
                record.source,
                record.source_repo,
                record.upstream_commit,
                record.upstream_path,
                record.license_evidence,
                record.retrieved_at,
                record.modifications,
                record.date_added,
                record.risk,
            ]
        )
    return buffer.getvalue()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not args.write and not args.check:
        parser.error("choose --write or --check")
    records = collect_records()
    targets = {
        repo_root() / "docs" / "PROVENANCE.md": render_markdown(records),
        repo_root() / "docs" / "provenance.csv": render_csv(records),
    }
    if args.write:
        for target, content in targets.items():
            target.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote {target}")
        return 0
    failures = 0
    for target, expected in targets.items():
        actual = target.read_text(encoding="utf-8-sig") if target.is_file() else ""
        if actual != expected:
            failures += 1
            print(f"stale: {target.relative_to(repo_root())}; run python scripts/build_provenance.py --write")
    if failures:
        return 1
    print("provenance inventory is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
