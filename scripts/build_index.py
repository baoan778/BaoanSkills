#!/usr/bin/env python3
from __future__ import annotations

import argparse
import sys
from collections import defaultdict

from _skill_utils import flatten, iter_skills, load_skill, metadata_of, normalized_license, repo_root


def family_for(name: str) -> str:
    if "local-kb" in name or "local-knowledge-base" in name:
        return "Local knowledge base"
    if name.startswith("ctf-") or name == "solve-challenge":
        return "CTF"
    if name.startswith("src-") or name in {"ldsk-src", "cnvd-src-reporting", "auto-specialty-routing-score"}:
        return "SRC and bounty workflows"
    if any(token in name for token in ("aws", "azure", "gcp", "cloud", "k8s", "container", "active-directory", "mtls", "ssh-penetration", "privilege-escalation")):
        return "Cloud, identity, and infrastructure"
    if any(token in name for token in ("reverse", "forensic", "malware", "firmware", "binary", "gdb", "wireshark", "memory-", "protocol-", "anti-reversing", "constant-time", "zeroize", "js-reverse")):
        return "Reverse engineering, forensics, and malware"
    if any(token in name for token in ("compliance", "privacy", "gdpr", "pci", "security-requirement", "security-career", "security-bluebook", "threat-", "attack-tree", "stride-")):
        return "Threat modeling, compliance, and governance"
    if any(token in name for token in ("ffuf", "burp", "semgrep", "metasploit", "shodan", "scanning", "vulnerability-scanner", "supply-chain", "protect-mcp", "sast", "secrets-management")):
        return "Tools, scanning, and supply chain"
    if name in {"007", "audit-skills", "langgpt", "combat-learning-value-refiner", "adhx", "aegisops-ai", "cred-omega"}:
        return "Meta-skills and umbrella workflows"
    return "Application security and code review"


def render() -> str:
    grouped: dict[str, list[tuple[str, str, str, str]]] = defaultdict(list)
    for skill_dir in iter_skills():
        doc = load_skill(skill_dir)
        fm = doc.frontmatter
        metadata = metadata_of(fm)
        name = str(fm.get("name", skill_dir.name))
        description = flatten(fm.get("description", ""))
        risk = flatten(metadata.get("risk", "unknown")) or "unknown"
        license_value = normalized_license(fm)
        grouped[family_for(name)].append((name, risk, license_value, description))

    total = sum(len(rows) for rows in grouped.values())
    lines = [
        "# Skill index",
        "",
        "> Generated by `scripts/build_index.py`. Do not edit manually.",
        f"> Total skills: **{total}**",
        "",
    ]
    for family in sorted(grouped):
        rows = sorted(grouped[family])
        lines.extend([
            f"## {family} ({len(rows)})",
            "",
            "| Skill | Risk | License | Description |",
            "|---|---|---|---|",
        ])
        for name, risk, license_value, description in rows:
            safe_description = description.replace("|", "\\|")
            lines.append(
                f"| [{name}](../skills/{name}/SKILL.md) | {risk} | {license_value} | {safe_description} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not args.write and not args.check:
        parser.error("choose --write or --check")
    target = repo_root() / "docs" / "SKILLS_INDEX.md"
    expected = render()
    if args.write:
        target.write_text(expected, encoding="utf-8", newline="\n")
        print(f"wrote {target}")
        return 0
    actual = target.read_text(encoding="utf-8-sig") if target.is_file() else ""
    if actual != expected:
        print("docs/SKILLS_INDEX.md is stale; run python scripts/build_index.py --write")
        return 1
    print("skill index is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
